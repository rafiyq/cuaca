pub fn get_ascii_icon(code: u32) -> AsciiIcon {
    match code {
        0 | 1 => CODE_SUNNY,
        2 => CODE_PARTLY_CLOUDY,
        3 => CODE_CLOUDY,
        4 => CODE_VERY_CLOUDY,
        5 | 10 | 45 => CODE_FOG,
        60 | 61 => CODE_LIGHT_RAIN,
        63 | 80 => CODE_HEAVY_RAIN,
        95 | 97 => CODE_THUNDERY_HEAVY_RAIN,
        _ => CODE_UNKNOWN,
    }
}
